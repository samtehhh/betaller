def q(s):
    assert '"' not in s and '$' not in s and '\\' not in s, s
    return '"' + s + '"'


def sq(s):
    return "'" + s.replace("'", "\\'") + "'"


master = json.load(open(f'{KEYS}/moves_v2_master.json', encoding='utf-8'))
assert list(master) == list(META), 'ids differ'
text = {'en': {k: v['en'] for k, v in master.items()},
        'tr': {k: v['tr'] for k, v in master.items()}}
for lang in LANGS[2:]:
    p = f'{KEYS}/moves_v2_{lang}.json'
    if os.path.exists(p):
        d = json.load(open(p, encoding='utf-8'))
        assert list(d) == list(META), (lang, 'ids differ')
        for k, v in d.items():
            assert len(v['steps']) == 4 and len(v['mistakes']) == 2, (lang, k)
            assert v['dose'] == master[k]['en']['dose'], (lang, k, v['dose'])
        text[lang] = d
have = [lang for lang in LANGS if lang in text]


def block(s, body, closing):
    """Puts [body] between the markers, just before the last [closing]."""
    if BEGIN in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        return s[:i] + BEGIN + body + END + s[j:]
    i = s.rindex(closing)
    return s[:i] + BEGIN + body + END + s[i:]


def edit(path, fn):
    s = open(path, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in s else '\n'
    s = fn(s.replace('\r\n', '\n'))
    open(path, 'w', encoding='utf-8', newline='').write(s.replace('\n', nl))


def constants(s):
    start = s.index('const List<Map<String, dynamic>> defaultRoutines = [')
    end = s.index('\n];', start) + 3
    body = ''
    for k, (cat, icon) in META.items():
        t = text['en'][k]
        body += (f"  {{\n    'id': '{k}',\n    'title': {sq(t['title'])},\n"
                 f"    'description':\n        {sq(t['desc'])},\n"
                 f"    'category': '{cat}',\n    'duration': '5 dk',\n"
                 f"    'icon': '{icon}',\n  }},\n")
    return s[:start] + block(s[start:end], body, '];') + s[end:]


def guides(s):
    a = s.index('const kNewMoveText =')
    b = s.index('const _guides =')
    c = s.index('ExerciseGuide? exerciseGuide(')
    rows = ''
    full = ''
    for k in META:
        rows += f'  "{k}": {{\n'
        full += f'  "{k}": {{\n'
        for lang in have:
            t = text[lang][k]
            rows += f'    "{lang}": [{q(t["title"])}, {q(t["desc"])}, {q(t["dose"])}],\n'
            steps = ', '.join(q(x) for x in t['steps'])
            mistakes = ', '.join(q(x) for x in t['mistakes'])
            full += f'    "{lang}": ExerciseGuide([{steps}], [{mistakes}], {q(t["tip"])}),\n'
        rows += '  },\n'
        full += '  },\n'
    return (s[:a] + block(s[a:b], rows, '};') + block(s[b:c], full, '};')
            + s[c:])


edit('lib/utils/constants.dart', constants)
edit('lib/utils/exercise_guides.dart', guides)
print('languages:', ' '.join(have))
