"""Writes the Nov 2026 moves into the app from tool/l10n_keys/moves_v2_*.json.

  python tool/moves_v2_gen.py

Reads moves_v2_master.json (en + tr) and any moves_v2_<lang>.json beside it,
and (re)writes the generated blocks in lib/utils/constants.dart and
lib/utils/exercise_guides.dart. Safe to run again: a block is replaced, not
added twice. Languages with no file fall back to English in the app.
"""
