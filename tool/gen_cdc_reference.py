"""Generate lib/utils/cdc_stature_lms.dart from the CDC 2000 stature-for-age CSV.

Usage:
  python -I tool/gen_cdc_reference.py path/to/statage.csv [lib/utils/cdc_stature_lms.dart]

The CSV is the official CDC file (https://www.cdc.gov/growthcharts/data/zscore/statage.csv)
with the columns Sex (1 = male, 2 = female), Agemos, L, M, S, P3 ... P97.
Every row is kept (24, 24.5, 25.5 ... 239.5, 240 months): the table is small
and the app interpolates linearly in months between rows.
"""
import csv
import sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "lib/utils/cdc_stature_lms.dart"

rows = {1: [], 2: []}
with open(src, newline="", encoding="utf-8-sig") as f:
    for r in csv.DictReader(f):
        sex = r.get("Sex", "").strip()
        if sex not in ("1", "2"):
            continue  # skip blank or repeated header lines
        rows[int(sex)].append(
            (float(r["Agemos"]), float(r["L"]), float(r["M"]), float(r["S"]))
        )

for sex, data in rows.items():
    data.sort()
    ages = [a for a, *_ in data]
    if len(ages) != len(set(ages)):
        sys.exit(f"duplicate Agemos rows for sex {sex}")
    if ages[0] != 24 or ages[-1] != 240:
        sys.exit(f"unexpected age range for sex {sex}: {ages[0]}..{ages[-1]}")


def table(name, data):
    lines = [f"const List<List<double>> {name} = ["]
    for a, l, m, s in data:
        lines.append(f"  [{a:g}, {l:.9g}, {m:.9g}, {s:.9g}],")
    lines.append("];")
    return "\n".join(lines)


body = f"""// GENERATED by tool/gen_cdc_reference.py from the CDC statage.csv. Do not edit.
//
// CDC 2000 growth charts, stature-for-age, LMS parameters, 2 to 20 years.
// Source: https://www.cdc.gov/growthcharts/percentile_data_files.htm
// Each row is [age in months, L, M, S]. M is the median height in cm.

{table("cdcStatureLmsMale", rows[1])}

{table("cdcStatureLmsFemale", rows[2])}
"""

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(body)
print(f"wrote {out}: male {len(rows[1])} rows, female {len(rows[2])} rows")
